test('a new draft and an unavailable applied draft both require an explicit handoff decision without replacing inputs',async({page})=>{
  await createPartialDraft(page)
  await page.getByLabel('草案目的地',{exact:true}).fill('TEST ONLY 原目的地')
  await page.getByLabel('草案出发日期',{exact:true}).fill('2026-10-20')
  await page.getByRole('button',{name:'保存补充与确认'}).click()
  await expect(page.locator('.draft-review .status-pill')).toContainText('第 2 版')
  await page.getByRole('button',{name:'填入表单并核对'}).click()
  const first=await currentTask(page)
  const form=page.getByRole('form',{name:'旅行规划',exact:true})
  const start=form.getByRole('button',{name:'开始规划',exact:true})
  await expect(form.getByLabel('目的地',{exact:true})).toHaveValue('TEST ONLY 原目的地')
  let posts=0
  page.on('request',request=>{if(request.method()==='POST'&&request.url().endsWith('/tasks'))posts++})
  await page.getByLabel('旅行需求',{exact:true}).fill('TEST ONLY 10月20日去杭州玩两天，博物馆，步行，预算800元，需要预约')
  await page.getByRole('button',{name:'创建新草案'}).click()
  await expect(page.getByText('已整理一份新草案，当前表单仍来自上一份。',{exact:true})).toBeVisible()
  const second=await currentTask(page)
  expect(second.draft_id).not.toBe(first.draft_id)
  await expect(start).toBeDisabled()
  await expect(form.getByLabel('目的地',{exact:true})).toHaveValue('TEST ONLY 原目的地')
  expect(posts).toBe(0)
  await page.getByRole('button',{name:'填入最新草案',exact:true}).click()
  await expect(form.getByLabel('目的地',{exact:true})).toHaveValue('杭州')
  await expect(start).toBeEnabled()
  // Opening a saved itinerary clears the current task using the normal UI;
  // the applied form remains independent of the itinerary currently displayed.
  await page.getByRole('button',{name:'已保存行程',exact:false}).first().click()
  await page.locator('.saved-card').first().click()
  await expect(page.getByRole('button',{name:'编辑行程',exact:true})).toBeVisible()
  await expect(page.locator('.task-id')).toHaveCount(0)
  const draftPath=`**/api/v1/travel/drafts/${second.draft_id}`
  // TEST ONLY read failure, without replacing the draft with fabricated data.
  await page.route(draftPath,route=>route.request().method()==='GET'
    ?route.fulfill({status:503,json:{error:{code:'draft_temporarily_unavailable',message:'TEST ONLY 草案读取暂不可用',retryable:true}}})
    :route.continue())
  await page.reload()
  await expect(page.getByText('已应用草案尚未同步，请恢复连接读取；也可明确保留当前表单条件。',{exact:true})).toBeVisible()
  await expect(form.getByLabel('目的地',{exact:true})).toHaveValue('杭州')
  await expect(start).toBeDisabled()
  expect(posts).toBe(0)
  await page.getByRole('button',{name:'保留当前表单',exact:true}).click()
  await expect(start).toBeEnabled()
  await expect(form.getByLabel('目的地',{exact:true})).toHaveValue('杭州')
  expect(posts).toBe(0)
})
