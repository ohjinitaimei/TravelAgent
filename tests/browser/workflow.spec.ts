import { test, expect, type Page } from '@playwright/test'

// The isolated browser service uses TEST ONLY model/provider inputs. This suite
// exercises its actual draft, task, persistence and adjustment APIs; no live API.
test.beforeEach(async({page,context})=>{
  await context.route(/https:\/\//,route=>route.abort())
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'这次，去哪里？'})).toBeVisible()
})

async function currentTask(page:Page) {
  const id=(await page.locator('.task-id').innerText()).replace(/^任务\s+/,'').split(' · ')[0].trim()
  const response=await page.request.get(`/api/v1/travel/tasks/${id}`)
  expect(response.ok()).toBeTruthy()
  return response.json()
}
async function itinerary(page:Page,id:string) {
  const response=await page.request.get(`/api/v1/travel/itineraries/${id}`)
  expect(response.ok()).toBeTruthy()
  return response.json()
}
async function createPartialDraft(page:Page) {
  await page.getByLabel('旅行需求',{exact:true}).fill('TEST ONLY 想逛博物馆，需要预约')
  await page.getByRole('button',{name:'整理为草案'}).click()
  await expect(page.getByRole('heading',{name:'待核对的需求草案'})).toBeVisible()
  const task=await currentTask(page)
  expect(task.kind).toBe('draft')
  expect(task.itinerary_id).toBeNull()
  return task.draft_id as string
}
async function fillBaseDraft(page:Page) {
  await page.getByLabel('草案目的地',{exact:true}).fill('TEST ONLY 测试城市')
  await page.getByLabel('草案出发日期',{exact:true}).fill('2026-10-20')
  await page.getByLabel('草案天数',{exact:true}).fill('2')
  await page.getByLabel('草案每天站数',{exact:true}).fill('1')
  await page.getByLabel('草案交通方式',{exact:true}).selectOption('walking')
  await page.getByLabel('保存地点关键词',{exact:true}).check()
  await page.getByRole('button',{name:'按草案天数创建空白逐日项',exact:true}).click()
}
async function fillDailyDraft(page:Page,partial=false) {
  await page.getByLabel('草案第 1 天开始',{exact:true}).fill('09:00')
  if(!partial)await page.getByLabel('草案第 1 天结束',{exact:true}).fill('17:00')
  await page.getByLabel('草案第 1 天默认停留（分钟）',{exact:true}).fill('50')
  await page.getByLabel('草案第 2 天开始',{exact:true}).fill('11:00')
  await page.getByLabel('草案第 2 天结束',{exact:true}).fill('18:00')
  await page.getByLabel('草案第 2 天默认停留（分钟）',{exact:true}).fill('70')
}

