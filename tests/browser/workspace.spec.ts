test('unsaved differences survive tabs and reload dismissal, and discard restores the saved version',async({page})=>{
  await openSeed(page)
  await page.getByRole('button',{name:'编辑行程',exact:true}).click()
  await page.getByLabel('用户录入费用').first().fill('0')
  await page.getByLabel('停留（分钟）',{exact:true}).first().fill('90')
  await page.getByLabel('移动 TEST ONLY fixture-a 到哪一天').selectOption('1')
  await page.locator('[data-stop-id="fixture-a"]').getByRole('button',{name:'移动',exact:true}).click()
  const changes=page.getByRole('region',{name:'本次编辑改动'})
  await expect(changes).toContainText('第 2 天第 3 站')
  await expect(changes).toContainText('90 分钟')
  await expect(changes).toContainText('0 元')
  await expect(page.locator('.travel-leg')).toHaveCount(0)
  await expect(page.locator('.route-workspace .map-caption')).toContainText('编辑地点预览')
  await page.getByRole('button',{name:'预算与约束',exact:false}).first().click()
  await expect(page.getByRole('status',{name:'未保存行程修改'})).toBeVisible()
  await page.getByRole('button',{name:'返回行程编辑',exact:true}).click()
  const dialogPromise=page.waitForEvent('dialog')
  // A dismissed beforeunload has no new load event to await.
  await page.evaluate(()=>{setTimeout(()=>location.reload(),0)})
  const browserDialog=await dialogPromise
  expect(browserDialog.type()).toBe('beforeunload')
  await browserDialog.dismiss()
  await expect(changes).toContainText('90 分钟')
  await page.getByRole('button',{name:'退出编辑',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'有未保存的行程修改'})
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button',{name:'继续编辑',exact:true})).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button',{name:'退出编辑',exact:true})).toBeFocused()
  await expect(changes).toContainText('90 分钟')
  await page.getByRole('button',{name:'退出编辑',exact:true}).click()
  await dialog.getByRole('button',{name:'放弃修改并退出编辑',exact:true}).click()
  await expect(changes).toHaveCount(0)
  await expect(page.getByRole('status',{name:'未保存行程修改'})).toHaveCount(0)
  await expect(page.locator('.timeline')).toContainText('TEST ONLY fixture-a')
  await expect(page.locator('.travel-leg')).toHaveCount(1)
})

